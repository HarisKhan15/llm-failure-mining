"""Compare newly collected responses (e.g. from Ollama) with the AIW reference data.

The main pipeline needs several models (grouped cross-validation by model) and
many long failed answers (clustering). A single new model has neither, so this
command answers the question that matters for one model:

    Does the new model fail in the same way as the 75 AIW models?

It compares accuracy and the error-type profile of the new data with
(a) all AIW models and (b) AIW models with fewer than 10B parameters.

Usage:
    python -m llm_failure_mining.compare --new data/collected/ollama_llama3.2_3b.json
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from .data import load_dataset
from .features import add_features
from .report import ERROR_ORDER, _md_table

PROJECT_ROOT = Path(__file__).resolve().parent.parent
log = logging.getLogger("llm_failure_mining")


def error_profile(df: pd.DataFrame) -> pd.Series:
    """Share of each error type among failed responses."""
    failures = df[~df["correct"]]
    if failures.empty:
        return pd.Series(0.0, index=ERROR_ORDER)
    return failures["error_type"].value_counts(normalize=True).reindex(ERROR_ORDER, fill_value=0.0)


def compare(new: pd.DataFrame, reference: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    groups = {
        "new_data": new,
        "aiw_all_models": reference,
        "aiw_small_models_<10B": reference[reference["size_bucket"] == "small_<10B"],
    }
    summary_rows = []
    for name, df in groups.items():
        siblings = df[df["problem_type"] == "aiw_siblings"]
        sib_fail = siblings[~siblings["correct"]]
        summary_rows.append(
            {
                "group": name,
                "models": df["model"].nunique(),
                "responses": len(df),
                "accuracy": round(float(df["correct"].mean()), 3),
                "accuracy_siblings": round(float(siblings["correct"].mean()), 3) if len(siblings) else None,
                "off_by_one_share_of_sibling_failures": round(float((sib_fail["error_type"] == "off_by_one_low").mean()), 3)
                if len(sib_fail) else None,
                "no_parsable_answer_share": round(float((df["error_type"] == "no_parsable_answer").mean()), 3),
            }
        )
    profiles = pd.DataFrame({name: error_profile(df) for name, df in groups.items()}).round(3)
    profiles.index.name = "error_type"
    return pd.DataFrame(summary_rows), profiles.reset_index()


def plot_profiles(profiles: pd.DataFrame, path: Path) -> None:
    data = profiles.set_index("error_type")
    fig, ax = plt.subplots(figsize=(9, 4.5))
    width = 0.27
    positions = range(len(data))
    for i, col in enumerate(data.columns):
        ax.bar([p + (i - 1) * width for p in positions], data[col] * 100, width=width, label=col)
    ax.set_xticks(list(positions))
    ax.set_xticklabels(data.index, rotation=30, ha="right", fontsize=8)
    ax.set_ylabel("Share of failed responses (%)")
    ax.set_title("Error profile: new data vs. AIW models")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def write_markdown(summary: pd.DataFrame, profiles: pd.DataFrame, new_path: Path, out: Path) -> Path:
    new_row = summary.iloc[0]
    lines = [
        "# Comparison: new responses vs. AIW reference",
        "",
        f"_Generated by `python -m llm_failure_mining.compare` from `{new_path.name}`._",
        "",
        "## Summary",
        _md_table(summary),
        "",
        "## Error profile among failed responses",
        _md_table(profiles),
        "",
        "![Error profile](comparison.png)",
        "",
        "## Notes",
        f"- The new data has {int(new_row['responses'])} responses. Shares based on few failures are uncertain.",
        "- Correctness for collected data is automatic (parsed number equals the right answer). "
        "The AIW labels also include the authors' manual checks, so the two are not labelled in exactly the same way.",
        "- A high `no_parsable_answer` share usually means the model ignored the `### Answer:` format, not that it reasoned worse.",
    ]
    path = out / "COMPARISON.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare collected responses with the AIW reference data.")
    parser.add_argument("--new", type=Path, required=True, help="collected JSON file in AIW format")
    parser.add_argument("--reference", type=Path, default=PROJECT_ROOT / "data" / "raw" / "AIW_AIW_plus.json")
    parser.add_argument("--output", type=Path, default=None, help="output folder (default results/compare_<name>)")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    try:
        new = add_features(load_dataset(args.new))
        reference = add_features(load_dataset(args.reference))
    except (FileNotFoundError, ValueError) as exc:
        log.error("Error: %s", exc)
        return 1

    out = args.output or PROJECT_ROOT / "results" / f"compare_{args.new.stem}"
    out.mkdir(parents=True, exist_ok=True)
    summary, profiles = compare(new, reference)
    summary.to_csv(out / "summary.csv", index=False)
    profiles.to_csv(out / "error_profiles.csv", index=False)
    plot_profiles(profiles, out / "comparison.png")
    report = write_markdown(summary, profiles, args.new, out)

    pd.set_option("display.width", 200)
    print(summary.to_string(index=False))
    print()
    print(profiles.to_string(index=False))
    log.info("\nReport: %s", report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
